    TRIM(USAGE_ID) AS USAGE_ID,
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    MONTH AS USAGE_MONTH,
    LOGIN_COUNT,
    API_CALLS,
    DATA_PROCESSED_GB,
    FEATURES_USED,
    SUPPORT_TICKETS
FROM CHURN_ANALYSIS.LANDING.LANDING_USAGE_METRICS
WHERE USAGE_ID IS NOT NULL
  AND CUSTOMER_ID IS NOT NULL
  