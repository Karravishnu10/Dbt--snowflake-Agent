{{ config(materialized='table') }}

WITH usage_summary AS (
    SELECT
        CUSTOMER_ID,
        SUM(LOGIN_COUNT) AS TOTAL_LOGINS,
        SUM(API_CALLS) AS TOTAL_API_CALLS,
        SUM(DATA_PROCESSED_GB) AS TOTAL_DATA_PROCESSED_GB,
        SUM(FEATURES_USED) AS TOTAL_FEATURES_USED,
        SUM(SUPPORT_TICKETS) AS USAGE_REPORTED_SUPPORT_TICKETS
    FROM {{ ref('stg_usage_metrics') }}
    GROUP BY CUSTOMER_ID
),

ticket_summary AS (
    SELECT
        CUSTOMER_ID,
        COUNT(*) AS TOTAL_SUPPORT_TICKETS,
        SUM(CASE WHEN PRIORITY = 'high' THEN 1 ELSE 0 END)
            AS HIGH_PRIORITY_TICKETS,
        SUM(CASE WHEN RESOLUTION_STATUS = 'open' THEN 1 ELSE 0 END)
            AS OPEN_SUPPORT_TICKETS
    FROM {{ ref('stg_support_tickets') }}
    GROUP BY CUSTOMER_ID
)

SELECT
    c.CUSTOMER_ID,
    COALESCE(u.TOTAL_LOGINS, 0) AS TOTAL_LOGINS,
    COALESCE(u.TOTAL_API_CALLS, 0) AS TOTAL_API_CALLS,
    COALESCE(u.TOTAL_DATA_PROCESSED_GB, 0) AS TOTAL_DATA_PROCESSED_GB,
    COALESCE(u.TOTAL_FEATURES_USED, 0) AS TOTAL_FEATURES_USED,
    COALESCE(u.USAGE_REPORTED_SUPPORT_TICKETS, 0)
        AS USAGE_REPORTED_SUPPORT_TICKETS,
    COALESCE(t.TOTAL_SUPPORT_TICKETS, 0) AS TOTAL_SUPPORT_TICKETS,
    COALESCE(t.HIGH_PRIORITY_TICKETS, 0) AS HIGH_PRIORITY_TICKETS,
    COALESCE(t.OPEN_SUPPORT_TICKETS, 0) AS OPEN_SUPPORT_TICKETS
FROM {{ ref('stg_customers') }} AS c
LEFT JOIN usage_summary AS u
    ON c.CUSTOMER_ID = u.CUSTOMER_ID
LEFT JOIN ticket_summary AS t
    ON c.CUSTOMER_ID = t.CUSTOMER_ID